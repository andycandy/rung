"""Explore: operate an app's UI to achieve a state delta when no trusted rung exists.

The model reads an accessibility snapshot and picks actions (goto/click/fill/select/check).
It may not declare success: the caller's independent check (`app.holds()`) runs after every
action. If the model is unavailable, gives up or runs out of budget, the step fails -- there
is no heuristic fallback.
"""
from __future__ import annotations

import secrets
import time
import urllib.parse
from dataclasses import dataclass, field

from rung import store
from rung.types import Delta, ExecResult


@dataclass
class Trace:
    actions: list = field(default_factory=list)
    pages: list = field(default_factory=list)
    llm_calls: int = 0
    gave_up: str = ""
    final: str = ""                                  # page path once the goal held
    refused: list = field(default_factory=list)      # actions the guard stopped


TRUE, FALSE = ("true", "1", "on", "yes", "checked"), ("false", "0", "off", "no", "unchecked", "")


def as_bool(v) -> bool | None:
    """A checkbox value as the model wrote it (True / "false" / "on" ...). bool("false") is True, so parse tokens."""
    if isinstance(v, bool):
        return v
    s = str(v if v is not None else "").strip().casefold()
    return True if s in TRUE else False if s in FALSE else None


def _norm(s) -> str:
    return str(s).strip().lstrip("#").strip().casefold()


def guard(a, el: dict | None, delta: Delta, values: dict) -> str | None:
    """What code lets the explorer do, whatever the model says. -> reason if refused.
    The model may only type values the task supplied (passwords are generated by code), pick a select
    option that is one of those values, change a checkbox only when the goal sets a true/false field,
    and navigate only within the app. Without this, a model that hit 'username taken' invented a new
    username and created an account nobody asked for."""
    given = {str(v) for v in values.values() if isinstance(v, (str, int)) and not isinstance(v, bool)}
    if a.action == "fill":
        if (el or {}).get("type") == "password" or a.value in (None, ""):
            return None
        if str(a.value) not in given:
            return f"fill {a.id} {a.value!r}: you may only enter the values given ({sorted(given)})"
    elif a.action == "select":
        opts = (el or {}).get("options") or []
        if a.value not in opts:
            return f"select {a.id} {a.value!r}: not one of this select's options {opts[:12]}"
        if _norm(a.value) not in {_norm(g) for g in given}:
            return f"select {a.id} {a.value!r}: you may only choose an option that is one of the values given ({sorted(given)})"
    elif a.action == "check":
        if as_bool(a.value) is None:
            return f"check {a.id} {a.value!r}: value must be true or false"
        if not any(isinstance(v, bool) for k, v in delta.expect.items() if k != "exists"):
            return f"check {a.id}: this goal sets no true/false field, so no checkbox may change"
    elif a.action == "goto":
        if not str(a.value or "").startswith("/"):
            return f"goto {a.value!r}: only paths within this app (starting with '/')"
    return None


def path_templates(pages: list[str], values: dict) -> list[str]:
    """Visited page paths with any segment equal to a task value replaced by its name
    ('/people/priya.sharma' -> '/people/{user}'). Structured URL handling only."""
    out = []
    for page in pages:
        segs = []
        for seg in page.split("?")[0].split("/"):
            name = next((k for k, v in values.items() if isinstance(v, str) and v and urllib.parse.unquote(seg) == v), None)
            segs.append("{" + name + "}" if name else seg)
        t = "/".join(segs)
        if t not in out:
            out.append(t)
    return out


def fill_templates(templates: list[str], values: dict) -> list[str]:
    out = []
    for t in templates:
        segs = []
        for seg in t.split("/"):
            if seg.startswith("{") and seg.endswith("}"):
                v = values.get(seg[1:-1])
                if not isinstance(v, str):
                    segs = None
                    break
                seg = urllib.parse.quote(v, safe="")
            segs.append(seg)
        if segs is not None:
            out.append("/".join(segs))
    return out


class LLMExplorer:
    """Model-driven exploration: one typed call per step, bounded scratchpad."""
    name = "explore:llm"

    def __init__(self, model, budget: int = 12, known_paths: list[str] | None = None, on_step=None):
        self.model, self.budget, self.known_paths, self.on_step = model, budget, known_paths or [], on_step

    def run(self, ab, delta: Delta, values: dict, check=None, start: str = "/") -> Trace:
        from rung.llm.calls import explore_step

        tr = Trace()
        ab.goto(start)
        history: list[str] = []
        # one initial password per exploration (forms ask for it twice): random, never shown to the model
        # or logged; the person resets it on first login
        secret = secrets.token_urlsafe(14) + "!9a"
        for _ in range(self.budget):
            snap = ab.snapshot()
            tr.pages.append(snap["url"])
            step = explore_step(self.model, delta, values, snap, history[-6:], self.known_paths)
            tr.llm_calls += 1
            if self.on_step:   # the model's decision and its stated reason, for the event log
                self.on_step({"page": snap["url"], "action": step.action, "reason": step.reason[:300],
                              "actions": [a.model_dump(exclude_none=True) for a in step.actions][:6]})
            if step.action == "done":
                if check is None or check():
                    tr.final = urllib.parse.urlsplit(ab.page.url).path
                    return tr
                history.append("you said done, but the independent check says the goal does NOT hold yet")
                continue
            if step.action == "give_up":
                tr.gave_up = step.reason or "model gave up"
                return tr
            types = {e["id"]: e.get("type") for e in snap["elements"]}
            els = {e["id"]: e for e in snap["elements"]}
            try:
                for a in step.actions or [step]:
                    if a.action != "goto" and a.id not in types:   # ids are the snapshot's, not the page's HTML ids
                        history.append(f"error: no element with id {a.id!r} on {snap['url']}; use the ids from Elements")
                        break
                    refused = guard(a, els.get(a.id), delta, values)
                    if refused:
                        tr.refused.append(refused)
                        history.append(f"refused: {refused}")
                        break
                    if a.action == "click":
                        before = ab.page.url
                        ab.click(a.id)
                        if ab.page.url != before:   # the rest of the batch referred to the page we just left
                            tr.actions.append((a.action, a.id, a.value))
                            history.append(f"click {a.id} on {snap['url']} -> navigated; re-read the new page")
                            break
                    elif a.action == "fill":
                        ab.fill(a.id, secret if types.get(a.id) == "password" else a.value)
                    elif a.action == "select":
                        ab.select(a.id, a.value)
                    elif a.action == "check":
                        ab.check(a.id, as_bool(a.value))
                    elif a.action == "goto":
                        ab.goto(a.value)
                    tr.actions.append((a.action, a.id, "<generated>" if types.get(a.id) == "password" else a.value))
                    history.append(f"{a.action} {a.id} {a.value or ''} on {snap['url']}")
            except Exception as ex:  # noqa: BLE001 -- first line only: Playwright's call log varies run to run
                history.append(f"error: {(str(ex).splitlines() or [type(ex).__name__])[0][:200]}")
            if check is not None and check():
                tr.final = urllib.parse.urlsplit(ab.page.url).path   # where the browser is once the change holds
                return tr
        tr.gave_up = "budget exhausted"
        return tr


def explore_with_model(ctx, app, delta: Delta, values: dict, shot_prefix: str) -> ExecResult:
    """Shared by every explorable adapter: record traffic, explore with the model, report.
    Any model failure (unavailable, invalid output after retries) fails the step."""
    t0 = time.time()
    if ctx.model is None:
        return ExecResult(ok=False, rung=LLMExplorer.name, detail="no model configured: UI exploration needs one (set RUNG_MODEL)")
    ab = app.ab(ctx)
    tag = f"explore-{secrets.token_hex(3)}"
    ab.start_recording(tag)
    # pages where verified changes were made in this app before, this entity first (any direction: add helps
    # remove; a change to a user's account points to the page where that user's memberships live too)
    nav_key = f"{app.name}:{delta.entity}"
    entities = [delta.entity] + [e for e in app.projection if e != delta.entity]
    known = [f"{e}: {p}" for e in entities for p in fill_templates(store.get_nav_paths(f"{app.name}:{e}"), values)]
    explorer = LLMExplorer(ctx.model, known_paths=known, on_step=lambda d: ctx.log("explore.step", {"delta": delta.describe(), **d}))
    check = lambda: app.holds(ctx, delta)[0]  # noqa: E731 -- independent goal check
    try:
        tr = explorer.run(ab, delta, values, check=check, start=app.HOME)
    except Exception as ex:  # noqa: BLE001
        ctx.log("llm.error", {"call": "explore_step", "error": f"{type(ex).__name__}: {ex}"})
        tr = Trace(gave_up=f"model error: {type(ex).__name__}: {ex}")
    if not tr.gave_up and tr.final:   # the run only ends without giving up when the independent check held
        store.put_nav_paths(nav_key, path_templates([tr.final], values))   # where the entity lives once changed, not the detours
    if tr.refused:
        ctx.log("explore.refused", {"delta": delta.describe(), "refused": tr.refused})
    rec = ab.stop_recording()
    shot = ab.screenshot(f"{shot_prefix}-{tag}")
    ctx.stats["explore_steps"] += 1
    return ExecResult(ok=not tr.gave_up, rung=explorer.name, detail=tr.gave_up or f"{len(tr.actions)} UI actions via {tr.pages}",
                      ms=int((time.time() - t0) * 1000), llm_calls=tr.llm_calls, recording=rec,
                      data={"actions": tr.actions, "pages": tr.pages, "screenshot": shot})
