#!/usr/bin/env bash
# End-to-end demo: seed the company, start the sandbox, then a cold run, a warm run and a tick.
# Writes the reports to docs/sample_report.md.
#
#   bash scripts/demo.sh            # offline mode
#   RUNG_MODEL=nim NVIDIA_API_KEY=... bash scripts/demo.sh
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=docs/sample_report.md
mkdir -p docs

# fresh company AND fresh agent state (no learned tools, runs or sessions), as the eval does
python -c "from eval.run_eval import reset; reset()" >/dev/null

SANDBOX_PID=""
if ! (exec 3<>/dev/tcp/127.0.0.1/7101) 2>/dev/null; then
  python -m sandbox.run_all >/dev/null 2>&1 &
  SANDBOX_PID=$!
  trap '[ -n "$SANDBOX_PID" ] && kill "$SANDBOX_PID"' EXIT
  for _ in $(seq 1 30); do (exec 3<>/dev/tcp/127.0.0.1/7101) 2>/dev/null && break; sleep 1; done
fi

section() {  # section <title> <command...>
  local title=$1; shift
  echo "== $title" >&2
  local t0=$SECONDS
  {
    echo "## $title"
    echo
    echo '```'
    echo "\$ python -m rung $*"
    python -m rung "$@"
    echo '```'
    echo
    echo "_wall time: $((SECONDS - t0)) s_"
    echo
  } >> "$OUT"
}

{
  echo "# Rung sample run"
  echo
  echo "Generated by \`scripts/demo.sh\` on $(date -u +%Y-%m-%dT%H:%MZ), model: \`${RUNG_MODEL:-offline}\`."
  echo
} > "$OUT"

section "1. Cold onboarding (explores the Chatter UI, learns its API)" \
  run "Please onboard Priya, she's joining Monday as a data analyst" --yes
section "2. Learned tools after the cold run" rungs
section "3. Warm onboarding (uses the learned API, no browser for writes)" \
  run "Onboard Karan Shah please, starts Monday" --yes
section "4. Clock jumps to Monday" clock 2026-10-12T09:30:00+05:30
section "5. Scheduled start-date steps fire" tick
section "6. All runs" runs

echo "wrote $OUT" >&2
